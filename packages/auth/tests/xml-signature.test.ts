// Signature verification
// ---------------------------------------------------------------------------

const { privateKey, publicKey } = generateKeyPairSync('rsa', { modulusLength: 2048 });

const PUBLIC_KEY_PEM = publicKey.export({ type: 'spki', format: 'pem' }).toString();

const DS = 'http://www.w3.org/2000/09/xmldsig#';

/**
 * Builds a signed document the way an IdP would, using this module's own canonical form.
 *
 * Circular for the "valid signature verifies" case, and deliberately so — see the file header. Its
 * real job is to produce a *correctly signed* document that the refusal cases can then damage in one
 * specific way each, so that what a test proves is "this particular tampering is caught" rather than
 * "something is wrong with this document".
 */
function signedDocument(options: {
  readonly assertionId?: string;
  readonly body?: string;
  readonly referenceUri?: string;
  readonly digestAlgorithm?: string;
  readonly signatureAlgorithm?: string;
  readonly canonicalizationAlgorithm?: string;
  readonly transforms?: readonly string[];
  /** Damage applied to the serialised XML *after* signing. */
  readonly tamper?: (xml: string) => string;
} = {}): { readonly xml: string; readonly assertionId: string } {
  const assertionId = options.assertionId ?? '_a1b2c3';
  const body = options.body ?? '<Subject>priya@example.com</Subject>';
  const digestAlgorithm = options.digestAlgorithm ?? 'http://www.w3.org/2001/04/xmlenc#sha256';
  const signatureAlgorithm =
    options.signatureAlgorithm ?? 'http://www.w3.org/2001/04/xmldsig-more#rsa-sha256';
  const canonicalizationAlgorithm =
    options.canonicalizationAlgorithm ?? 'http://www.w3.org/2001/10/xml-exc-c14n#';
  const transforms = options.transforms ?? [
    'http://www.w3.org/2000/09/xmldsig#enveloped-signature',
    'http://www.w3.org/2001/10/xml-exc-c14n#',
  ];

  // 1. Digest the assertion with no Signature inside it, exactly as the enveloped transform says.
  const unsigned = `<Assertion xmlns="urn:oasis:names:tc:SAML:2.0:assertion" ID="${assertionId}">${body}</Assertion>`;
  const digest = createHashDigest(canonicalizeExclusive(parseXml(unsigned)));

  const signedInfo =
    `<ds:SignedInfo xmlns:ds="${DS}">` +
    `<ds:CanonicalizationMethod Algorithm="${canonicalizationAlgorithm}"></ds:CanonicalizationMethod>` +
    `<ds:SignatureMethod Algorithm="${signatureAlgorithm}"></ds:SignatureMethod>` +
    `<ds:Reference URI="${options.referenceUri ?? `#${assertionId}`}">` +
    `<ds:Transforms>${transforms.map((t) => `<ds:Transform Algorithm="${t}"></ds:Transform>`).join('')}</ds:Transforms>` +
    `<ds:DigestMethod Algorithm="${digestAlgorithm}"></ds:DigestMethod>` +
    `<ds:DigestValue>${digest}</ds:DigestValue>` +
    `</ds:Reference></ds:SignedInfo>`;

  // 2. Sign the canonical SignedInfo.
  const signer = createSign('RSA-SHA256');
  signer.update(canonicalizeExclusive(parseXml(signedInfo)), 'utf8');
  const signatureValue = signer.sign(privateKey, 'base64');

  const signature = `<ds:Signature xmlns:ds="${DS}">${signedInfo}<ds:SignatureValue>${signatureValue}</ds:SignatureValue></ds:Signature>`;
  const xml = `<Assertion xmlns="urn:oasis:names:tc:SAML:2.0:assertion" ID="${assertionId}">${body}${signature}</Assertion>`;

  return { xml: options.tamper ? options.tamper(xml) : xml, assertionId };
}

function createHashDigest(canonical: string): string {
  // Local rather than imported so the test states its own expectation of the digest input.
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { createHash } = require('node:crypto') as typeof import('node:crypto');
  return createHash('sha256').update(canonical, 'utf8').digest('base64');
}

const verify = (xml: string, certificate = PUBLIC_KEY_PEM) => {
  const document = parseXml(xml);
  return verifyXmlSignature({ document, signed: document, certificate });
};

describe('signature verification accepts a correctly signed assertion', () => {
  it('verifies the digest and the signature together', () => {
    // Circular by construction (see the header) — its value is as the control the cases below vary.
    expect(verify(signedDocument().xml)).toEqual({ ok: true });
  });
});

describe('signature verification refuses a tampered assertion', () => {
  it('refuses altered content, with the signature left intact', () => {
    // The signature still verifies over SignedInfo; the *digest* no longer matches the content. This
    // is the attack that matters, and the reason the digest is checked separately.
    const { xml } = signedDocument({
      tamper: (raw) => raw.replace('priya@example.com', 'attacker@example.com'),
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'digest_mismatch' });
  });

  it('refuses an added attribute, which changes the canonical form', () => {
    const { xml } = signedDocument({
      tamper: (raw) => raw.replace('<Subject>', '<Subject role="owner">'),
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'digest_mismatch' });
  });

  it('refuses a corrupted SignatureValue', () => {
    const { xml } = signedDocument({
      tamper: (raw) =>
        raw.replace(/<ds:SignatureValue>(.)/, (_match, first: string) =>
          `<ds:SignatureValue>${first === 'A' ? 'B' : 'A'}`,
        ),
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'bad_signature' });
  });

  it('refuses a signature made by a different key', () => {
    const other = generateKeyPairSync('rsa', { modulusLength: 2048 });
    const otherPem = other.publicKey.export({ type: 'spki', format: 'pem' }).toString();

    expect(verify(signedDocument().xml, otherPem)).toEqual({ ok: false, reason: 'bad_signature' });
  });
});

describe('signature verification refuses the wrapping attacks', () => {
  it('refuses a document where two elements carry the referenced id', () => {
    /**
     * The classic XML signature wrapping attack.
     *
     * The attacker keeps the legitimately signed assertion and adds a second element with the same
     * id holding their own claims. A verifier that resolved the reference to the *first* match would
     * confirm the signature while the application read the second.
     */
    const { xml, assertionId } = signedDocument();
    const wrapped = xml.replace(
      '<Subject>',
      `<Decoy ID="${assertionId}"><Subject>attacker@example.com</Subject></Decoy><Subject>`,
    );

    expect(verify(wrapped)).toEqual({ ok: false, reason: 'duplicate_id' });
  });

  it('refuses a signature that references an element other than the one being verified', () => {
    const { xml } = signedDocument({ referenceUri: '#somewhere-else' });

    expect(verify(xml)).toEqual({ ok: false, reason: 'reference_mismatch' });
  });

  it('refuses an empty reference URI, which would claim the whole document', () => {
    const { xml } = signedDocument({ referenceUri: '' });

    expect(verify(xml)).toEqual({ ok: false, reason: 'reference_mismatch' });
  });

  it('refuses a signature that is not a direct child of what it signs', () => {
    // Moved one level down. The signature is still present and still valid over its own SignedInfo,
    // so only the structural check catches this.
    const { xml } = signedDocument();
    const moved = xml
      .replace(/<ds:Signature[\s\S]*<\/ds:Signature>/, '')
      .replace('<Subject>', '<Wrapper>' + (xml.match(/<ds:Signature[\s\S]*<\/ds:Signature>/)?.[0] ?? '') + '</Wrapper><Subject>');

    expect(verify(moved)).toEqual({ ok: false, reason: 'signature_not_enveloped' });
  });

  it('refuses an assertion with no signature at all', () => {
    const document = parseXml('<Assertion xmlns="urn:oasis:names:tc:SAML:2.0:assertion" ID="_x"><Subject>a</Subject></Assertion>');

    expect(verifyXmlSignature({ document, signed: document, certificate: PUBLIC_KEY_PEM })).toEqual({
      ok: false,
      reason: 'no_signature',
    });
  });
});

describe('signature verification refuses algorithms outside the profile', () => {
  it('refuses SHA-1 digests', () => {
    const { xml } = signedDocument({ digestAlgorithm: 'http://www.w3.org/2000/09/xmldsig#sha1' });

    expect(verify(xml)).toEqual({ ok: false, reason: 'unsupported_digest_algorithm' });
  });

  it('refuses RSA-SHA1 signatures', () => {
    const { xml } = signedDocument({
      signatureAlgorithm: 'http://www.w3.org/2000/09/xmldsig#rsa-sha1',
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'unsupported_signature_algorithm' });
  });

  it('refuses inclusive canonicalisation, which this module does not implement', () => {
    // Refusing is the only honest answer: pretending to verify inclusive c14n with an exclusive
    // implementation would compare a digest against bytes nobody produced.
    const { xml } = signedDocument({
      canonicalizationAlgorithm: 'http://www.w3.org/TR/2001/REC-xml-c14n-20010315',
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'unsupported_canonicalization' });
  });

  it('refuses an unknown transform rather than ignoring it', () => {
    const { xml } = signedDocument({
      transforms: [
        'http://www.w3.org/2000/09/xmldsig#enveloped-signature',
        'http://www.w3.org/TR/1999/REC-xslt-19991116',
      ],
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'unsupported_transforms' });
  });

  it('refuses a transform pipeline in the wrong order', () => {
    const { xml } = signedDocument({
      transforms: [
        'http://www.w3.org/2001/10/xml-exc-c14n#',
        'http://www.w3.org/2000/09/xmldsig#enveloped-signature',
      ],
    });

    expect(verify(xml)).toEqual({ ok: false, reason: 'unsupported_transforms' });
  });

  it('refuses an empty certificate', () => {
    expect(verify(signedDocument().xml, '   ')).toEqual({ ok: false, reason: 'bad_certificate' });
  });

  it('refuses a certificate that is not a key at all, rather than throwing', () => {
    expect(verify(signedDocument().xml, 'not-a-certificate')).toEqual({
      ok: false,
      reason: 'bad_certificate',
    });
  });
});

describe('findElementsById', () => {
  it('collects every match rather than the first, which is what makes duplicates visible', () => {
    const document = parseXml('<r><a ID="x"/><b Id="x"/><c id="x"/><d ID="y"/></r>');

    expect(findElementsById(document, 'x')).toHaveLength(3);
    expect(findElementsById(document, 'y')).toHaveLength(1);
    expect(findElementsById(document, 'z')).toHaveLength(0);
  });
});
